"""Summarize pqt run logs into a per-session, per-symbol table and append it to logs/session_history.md.

    python research/summarize_log.py logs/*.log            # print
    python research/summarize_log.py logs/*.log --write    # also rewrite logs/session_history.md
"""
import collections, re, sys, os

def parse(paths):
    sess = {}
    for path in paths:
        cur = run = None
        for line in open(path, errors="replace"):
            m = re.search(r"START (\w+) mode, session ([\w-]+).*run (\w+), params (\{.*\})", line)
            if m:
                cur, run = m.group(2), m.group(3)
                s = sess.setdefault(cur, dict(mode=m.group(1), runs=set(), params=m.group(4), sym=collections.OrderedDict(),
                                              blocks=0, news=0, recon=0, rejects="", end="", file=os.path.basename(path), first_min=None))
                s["runs"].add(run); s["mode"] = m.group(1); s["params"] = m.group(4)
                continue
            m = re.search(r"connected as \w+: session ([\w-]+)", line)
            if m:
                cur = m.group(1)
            m = re.search(r"NEW SESSION", line)
            if cur is None:
                continue
            s = sess.setdefault(cur, dict(mode="?", runs=set(), params="", sym=collections.OrderedDict(), blocks=0, news=0,
                                          recon=0, rejects="", end="", file=os.path.basename(path), first_min=None))
            m = re.search(r"BLOCK min (\d+)-\d+ (\w+): filled (\d+) sh .*clean (\d+) sh, NET [^(]*\(\$([-\d.]+)\).*share of market (\d+)%.*\| (\w+)", line)
            if m:
                mn, sym = int(m.group(1)), m.group(2)
                s["first_min"] = mn if s["first_min"] is None else min(s["first_min"], mn)
                d = s["sym"].setdefault(sym, dict(sh=0, usd=0.0, n=0, part=[], modes=collections.Counter()))
                d["sh"] += int(m.group(4)); d["usd"] += float(m.group(5)); d["n"] += 1
                d["part"].append(int(m.group(6))); d["modes"][m.group(7)] += 1
                s["blocks"] += 1
            if "NEWS at batch" in line: s["news"] += 1
            if "RECONNECTED" in line: s["recon"] += 1
            m = re.search(r"END: pos (\{[^}]*\}), est PnL \$([-\d.]+).*rejects (.*)$", line)
            if m: s["end"] = f"est PnL ${m.group(2)}, end pos {m.group(1)}"; s["rejects"] = m.group(3).strip()
    return sess

def render(sess):
    out = ["# Session history (generated by research/summarize_log.py)", "",
           "NET = mid-markout proxy after fees, 60 s after each fill (not the official score).", ""]
    for name, s in sess.items():
        if not s["sym"]:
            continue
        if all(d["sh"] == 0 for d in s["sym"].values()):
            out.append(f"## {name}: no scored fills (monitor bug before the 9:30 fix, or no trading)\n")
            continue
        tot = sum(d["usd"] for d in s["sym"].values())
        mins = max(d["n"] for d in s["sym"].values()) * 2
        out.append(f"## {name} ({s['mode']}, runs {', '.join(sorted(s['runs']))}, log {s['file']})")
        out.append(f"Scored blocks from minute {s['first_min']}, ~{mins} min | proxy total **${tot:,.0f}** | news {s['news']} | reconnects {s['recon']}")
        if s["end"]: out.append(f"End: {s['end']} | rejects {s['rejects']}")
        out.append("")
        out.append("| symbol | clean shares | proxy $ | c/share | avg market share | modes |")
        out.append("|---|---|---|---|---|---|")
        for sym, d in s["sym"].items():
            cps = d["usd"] * 100 / d["sh"] if d["sh"] else 0
            part = sum(d["part"]) / len(d["part"]) if d["part"] else 0
            out.append(f"| {sym} | {d['sh']:,} | {d['usd']:+,.0f} | {cps:+.2f} | {part:.0f}% | {dict(d['modes'])} |")
        out.append("")
    return "\n".join(out)

if __name__ == "__main__":
    paths = [p for p in sys.argv[1:] if not p.startswith("--")]
    text = render(parse(paths))
    print(text)
    if "--write" in sys.argv:
        os.makedirs("logs", exist_ok=True)
        open("logs/session_history.md", "w").write(text + "\n")
